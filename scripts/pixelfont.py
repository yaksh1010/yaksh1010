HEIGHT = 7


def glyph(char):
    return GLYPHS.get(char.upper(), GLYPHS["?"])


def text_width(text, scale, spacing=1):
    """Width in user units of `text` drawn with pixels of size `scale`."""
    if not text:
        return 0
    columns = sum(len(glyph(c)[0]) for c in text) + spacing * (len(text) - 1)
    return columns * scale


def text_path(text, x, y, scale, spacing=1):
    """SVG path data for `text` with its top-left corner at (x, y). Runs of pixels are merged."""
    parts = []
    cursor = x
    for char in text:
        rows = glyph(char)
        for row_index, row in enumerate(rows):
            column = 0
            while column < len(row):
                if row[column] == "#":
                    start = column
                    while column < len(row) and row[column] == "#":
                        column += 1
                    px = cursor + start * scale
                    py = y + row_index * scale
                    run = (column - start) * scale
                    parts.append(f"M{fmt(px)} {fmt(py)}h{fmt(run)}v{fmt(scale)}h-{fmt(run)}z")
                else:
                    column += 1
        cursor += (len(rows[0]) + spacing) * scale
    return "".join(parts)


def fmt(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")
